import mk.ukim.finki.exam_schedule.model.ExamWorkflowStatus;
import mk.ukim.finki.exam_schedule.model.ExamType;
import mk.ukim.finki.exam_schedule.model.SubjectExam;
import mk.ukim.finki.exam_schedule.model.YearExamSession;
import mk.ukim.finki.exam_schedule.model.exceptions.InvalidYearExamSessionException;
import mk.ukim.finki.exam_schedule.repository.SubjectExamRepository;
import mk.ukim.finki.exam_schedule.repository.YearExamSessionRepository;
import mk.ukim.finki.exam_schedule.service.scheduling.ScheduleGenerationService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.stereotype.Controller;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.util.List;

@Controller
@RequestMapping("/admin/scheduling")
public class SchedulingController {

    private static final Logger log = LoggerFactory.getLogger(SchedulingController.class);

    private final ScheduleGenerationService scheduleGenerationService;
    private final YearExamSessionRepository yearExamSessionRepository;
    private final SubjectExamRepository subjectExamRepository;

    public SchedulingController(ScheduleGenerationService scheduleGenerationService,
                                YearExamSessionRepository yearExamSessionRepository,
                                SubjectExamRepository subjectExamRepository) {
        this.scheduleGenerationService = scheduleGenerationService;
        this.yearExamSessionRepository = yearExamSessionRepository;
        this.subjectExamRepository = subjectExamRepository;
    }

    @PreAuthorize("hasRole('ADMIN')")
    @PostMapping("/generate")
    public String generate(@RequestParam String yes) {
        try {
            List<SubjectExam> generated = scheduleGenerationService.generateForSession(yes);
            if (generated.isEmpty()) {
                return "redirect:/admin/subject-exam?error=NoExamsToGenerateForSession:" + yes;
            }
            return "redirect:/admin/subject-exam?error=GenerateSuccessForSession:" + yes + "(" + generated.size() + ")";
        } catch (Exception ex) {
            log.error("Schedule generation failed for session {}", yes, ex);
            String reason = ex.getMessage() == null || ex.getMessage().isBlank()
                    ? ex.getClass().getSimpleName()
                    : ex.getMessage();
            String encodedReason = URLEncoder.encode(reason, StandardCharsets.UTF_8);
            return "redirect:/admin/subject-exam?error=GenerateFailedForSession:" + yes + ":" + encodedReason;
        }
    }

    @PreAuthorize("hasRole('ADMIN')")
    @PostMapping("/finalize")
    public String finalizeSchedule(@RequestParam String yes) {
        YearExamSession session = yearExamSessionRepository.findById(yes)
                .orElseThrow(InvalidYearExamSessionException::new);

        List<SubjectExam> exams = subjectExamRepository.findAllBySession(session);
        boolean hasIncomplete = exams.stream().anyMatch(this::isIncompleteForFinalization);
        if (hasIncomplete) {
            return "redirect:/admin/subject-exam?error=FinalizeBlockedIncompleteExams:" + yes;
        }

        session.setFinalizedAt(LocalDateTime.now());
        yearExamSessionRepository.save(session);

        exams.forEach(exam -> exam.setWorkflowStatus(ExamWorkflowStatus.FINALIZED));
        subjectExamRepository.saveAll(exams);
        return "redirect:/admin/subject-exam";
    }

    private boolean isIncompleteForFinalization(SubjectExam exam) {
        if (exam.getFromTime() == null || exam.getToTime() == null) {
            return true;
        }
        ExamType type = exam.getDefinition().getType();
        boolean needsRoom = type == ExamType.CLASSROOM || type == ExamType.LAB;
        return needsRoom && (exam.getRooms() == null || exam.getRooms().isEmpty());
    }
}





